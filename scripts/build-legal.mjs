// Generates legal/*.html (hostable pages) and src/content/legal.generated.ts (in-app copies)
// from the Markdown sources in legal/*.md, so there is a single source of truth.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const docs = [
  { key: 'privacy', file: 'privacy', title: 'Privacy Policy' },
  { key: 'terms', file: 'terms', title: 'Terms of Use' },
];

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function inline(text) {
  return escapeHtml(text).replace(/(https?:\/\/[^\s)]+)/g, '<a href="$1">$1</a>');
}

function markdownToHtml(md) {
  const blocks = md.split(/\n{2,}/).map((b) => b.trim()).filter(Boolean);
  return blocks
    .map((block) => {
      if (block.startsWith('# ')) return `<h1>${inline(block.slice(2))}</h1>`;
      if (block.startsWith('## ')) return `<h2>${inline(block.slice(3))}</h2>`;
      if (block.startsWith('### ')) return `<h3>${inline(block.slice(4))}</h3>`;
      if (block.startsWith('- ')) {
        const items = block.split('\n').map((l) => `<li>${inline(l.replace(/^- /, ''))}</li>`);
        return `<ul>${items.join('')}</ul>`;
      }
      return `<p>${inline(block.replace(/\n/g, ' '))}</p>`;
    })
    .join('\n');
}

function page(title, body) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Billnest ${title}</title>
<style>
  :root { color-scheme: light dark; --bg:#F6F5F0; --fg:#14201A; --muted:#5B6B63; --link:#1F7A5C; --card:#FFFFFF; --border:#E0E5DF; }
  @media (prefers-color-scheme: dark) { :root { --bg:#0F1613; --fg:#F2F5F1; --muted:#A6B3AA; --link:#4CC39A; --card:#182019; --border:#2B372F; } }
  body { margin:0; background:var(--bg); color:var(--fg); font:16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }
  main { max-width: 720px; margin: 0 auto; padding: 32px 16px 64px; }
  article { background: var(--card); border: 1px solid var(--border); border-radius: 16px; padding: 24px; }
  h1 { font-size: 28px; letter-spacing: -0.5px; margin: 0 0 8px; }
  h2 { font-size: 20px; margin: 28px 0 8px; }
  h3 { font-size: 17px; margin: 20px 0 6px; }
  p, li { color: var(--fg); }
  a { color: var(--link); word-break: break-all; }
  footer { color: var(--muted); font-size: 13px; margin-top: 24px; text-align: center; }
</style>
</head>
<body>
<main>
<article>
${body}
</article>
<footer>Billnest · Private, offline subscription tracking</footer>
</main>
</body>
</html>
`;
}

// HTML goes to docs/ so the folder can be published as-is with GitHub Pages ("Deploy from a branch", folder /docs).
const htmlDir = join(root, 'docs');
mkdirSync(htmlDir, { recursive: true });

const generated = {};
for (const d of docs) {
  const md = readFileSync(join(root, 'legal', `${d.file}.md`), 'utf8').replace(/\r\n/g, '\n');
  const updatedMatch = /Last updated:\s*(.+)/.exec(md);
  writeFileSync(join(htmlDir, `${d.file}.html`), page(d.title, markdownToHtml(md)));
  generated[d.key] = { title: d.title, updated: updatedMatch ? updatedMatch[1].trim() : '', markdown: md };
}

writeFileSync(
  join(htmlDir, 'index.html'),
  page(
    'Legal',
    '<h1>Billnest</h1><p>Private, offline subscription tracking for iPhone and Android.</p><ul><li><a href="privacy.html">Privacy Policy</a></li><li><a href="terms.html">Terms of Use</a></li></ul>',
  ),
);

const ts = `// Generated by scripts/build-legal.mjs from legal/*.md. Do not edit by hand.
export interface LegalDoc {
  title: string;
  updated: string;
  markdown: string;
}

export const LEGAL_DOCS: Record<'privacy' | 'terms', LegalDoc> = ${JSON.stringify(generated, null, 2)};
`;
mkdirSync(join(root, 'src', 'content'), { recursive: true });
writeFileSync(join(root, 'src', 'content', 'legal.generated.ts'), ts);
console.log('Wrote docs/privacy.html, docs/terms.html, docs/index.html and src/content/legal.generated.ts');
